package ifeel.shubham.mykotlinjourney.lesson02

fun main() {
    // In kotlin the data type is decided upon its value.
    val myNum = 5             // Int
    val myDoubleNum = 5.99    // Double
    val myLetter = 'D'        // Char
    val myBoolean = true      // Boolean
    val myText = "Hello"      // String

    // We can also specify the datatype
    val myNum1: Int = 5                // Int
    val myDoubleNum1: Double = 5.99    // Double
    val myLetter1: Char = 'D'          // Char
    val myBoolean1: Boolean = true     // Boolean
    val myText1: String = "Hello"      // String

    // print all
    println(myNum)
    println(myDoubleNum)
    println(myLetter)
    println(myBoolean)
    println(myText)

    println(myNum1)
    println(myDoubleNum1)
    println(myLetter1)
    println(myBoolean1)
    println(myText1)
}