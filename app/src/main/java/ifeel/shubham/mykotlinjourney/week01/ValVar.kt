package ifeel.shubham.mykotlinjourney.week01

fun main() {
    // val
    // once assigned value cannot be changed
    val name = "Shubham"
    // name = "Raj" [This is not possible]
    println("My name is $name")

    // var
    // once assigned it can be edited easily
    var age = 21
    age = age+1 // mutable
    println("My age is $age")
}