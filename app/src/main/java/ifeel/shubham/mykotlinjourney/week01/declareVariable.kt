fun main() {
    // declaring a val without assigning any value to it
    val score: Int
    val input = 20
    score = 100 * input
    println("Score is: $score")

    // declaring var w/o assigning any value to it
    var name: String
    name = "Shubham"
    println("My name is $name")
}